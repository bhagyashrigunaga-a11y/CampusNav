export function clientDijkstra(nodes, edges, sourceId, destinationId, accessible = false, algorithm = 'dijkstra') {
  const adj = new Map();
  const nodeMap = new Map();
  const unavailableNodeIds = new Set(nodes.filter(n =>
    n.is_available === false || n.is_available === 0 || n.is_available === '0' ||
    n.availability_status === 'unavailable'
  ).map(n => n.id));

  for (const n of nodes) {
    adj.set(n.id, []);
    nodeMap.set(n.id, n);
  }

  for (const edge of edges) {
    if (edge.is_blocked === true || edge.is_blocked === 1 || edge.is_blocked === '1' ||
        unavailableNodeIds.has(edge.source_node_id) || unavailableNodeIds.has(edge.target_node_id)) {
      continue;
    }

    let w = Number(edge.weight) || 1;
    if (accessible && (edge.type === 'staircase' || edge.type === 'stairs')) {
      w += 10000; // Algorithm 1 penalty
    }

    if (adj.has(edge.source_node_id)) {
      adj.get(edge.source_node_id).push({
        targetId: edge.target_node_id,
        weight: w,
        rawWeight: Number(edge.weight) || 1,
        type: edge.type
      });
    }

    if (edge.bidirectional !== false && edge.bidirectional !== 0) {
      if (adj.has(edge.target_node_id)) {
        adj.get(edge.target_node_id).push({
          targetId: edge.source_node_id,
          weight: w,
          rawWeight: Number(edge.weight) || 1,
          type: edge.type
        });
      }
    }
  }

  if (!nodeMap.has(sourceId) || !nodeMap.has(destinationId)) {
    return { success: false, error: 'Source or destination node not found in campus graph.' };
  }
  if (unavailableNodeIds.has(sourceId) || unavailableNodeIds.has(destinationId)) {
    return { success: false, error: 'This location is currently unavailable.' };
  }
  if (sourceId === destinationId) {
    const node = nodeMap.get(sourceId);
    return {
      success: true,
      algorithm,
      totalCost: 0,
      walkingTimeSeconds: 0,
      isAccessible: true,
      usesStairs: false,
      usesLift: false,
      pathNodeIds: [sourceId],
      pathNodes: [node],
      pathEdges: [],
      instructions: [{ step: 1, floor: node.floor_id, text: `You are already at ${node.name}.` }]
    };
  }

  const heuristic = algorithm === 'astar'
    ? createClientHeuristic(nodes, edges, destinationId)
    : () => 0;
  const dist = new Map();
  const rawDist = new Map();
  const priority = new Map();
  const prev = new Map();
  const unvisited = new Set(nodes.map(n => n.id));

  for (const n of nodes) {
    dist.set(n.id, Infinity);
    rawDist.set(n.id, Infinity);
    priority.set(n.id, Infinity);
  }

  dist.set(sourceId, 0);
  rawDist.set(sourceId, 0);
  priority.set(sourceId, heuristic(sourceId));

  while (unvisited.size > 0) {
    let curr = null;
    let minD = Infinity;

    for (const id of unvisited) {
      const d = priority.get(id);
      if (d < minD) {
        minD = d;
        curr = id;
      }
    }

    if (curr === null || minD === Infinity || curr === destinationId) break;
    unvisited.delete(curr);

    const neighbors = adj.get(curr) || [];
    for (const nb of neighbors) {
      if (!unvisited.has(nb.targetId)) continue;
      const alt = minD + nb.weight;
      if (alt < dist.get(nb.targetId)) {
        dist.set(nb.targetId, alt);
        rawDist.set(nb.targetId, (rawDist.get(curr) || 0) + nb.rawWeight);
        priority.set(nb.targetId, alt + heuristic(nb.targetId));
        prev.set(nb.targetId, { from: curr, edge: nb });
      }
    }
  }

  if (dist.get(destinationId) === Infinity) {
    return { success: false, error: 'No traversable route found between source and destination.' };
  }

  const pathNodeIds = [];
  const pathEdges = [];
  let at = destinationId;
  let usesStairs = false;
  let usesLift = false;

  while (at && at !== sourceId) {
    pathNodeIds.unshift(at);
    const step = prev.get(at);
    if (!step) break;
    pathEdges.unshift(step.edge);
    if (step.edge.type === 'staircase' || step.edge.type === 'stairs') usesStairs = true;
    if (step.edge.type === 'lift') usesLift = true;
    at = step.from;
  }
  pathNodeIds.unshift(sourceId);

  const totalCost = rawDist.get(destinationId) || 0;
  const pathNodes = pathNodeIds.map(id => nodeMap.get(id)).filter(Boolean);

  const instructions = pathNodes.map((n, i) => {
    if (i === 0) return { step: 1, floor: n.floor_id, text: `Start at ${n.name}` };
    if (i === pathNodes.length - 1) return { step: i + 1, floor: n.floor_id, text: `Arrived at destination: ${n.name}` };
    return { step: i + 1, floor: n.floor_id, text: `Proceed to ${n.name}` };
  });

  return {
    success: true,
    algorithm,
    totalCost,
    walkingTimeSeconds: Math.round(totalCost / 1.2),
    isAccessible: !usesStairs,
    usesStairs,
    usesLift,
    pathNodeIds,
    pathNodes,
    pathEdges,
    instructions
  };
}

function createClientHeuristic(nodes, edges, destinationId) {
  const nodeMap = new Map(nodes.map(node => [node.id, node]));
  const destination = nodeMap.get(destinationId);
  if (!destination) return () => 0;
  const destinationX = Number(destination.x);
  const destinationY = Number(destination.y);
  if (!Number.isFinite(destinationX) || !Number.isFinite(destinationY)) return () => 0;

  let minimumCostPerMapUnit = Infinity;
  for (const edge of edges) {
    if (edge.is_blocked === true || edge.is_blocked === 1 || edge.is_blocked === '1') continue;
    const from = nodeMap.get(edge.source_node_id);
    const to = nodeMap.get(edge.target_node_id);
    if (!from || !to) continue;
    const coordinates = [Number(from.x), Number(from.y), Number(to.x), Number(to.y)];
    if (!coordinates.every(Number.isFinite)) continue;
    const distance = Math.hypot(coordinates[0] - coordinates[2], coordinates[1] - coordinates[3]);
    const weight = Number(edge.weight);
    if (distance > 0 && Number.isFinite(weight) && weight >= 0) {
      minimumCostPerMapUnit = Math.min(minimumCostPerMapUnit, weight / distance);
    }
  }
  if (!Number.isFinite(minimumCostPerMapUnit)) return () => 0;

  return nodeId => {
    const node = nodeMap.get(nodeId);
    if (!node || node.floor_id !== destination.floor_id) return 0;
    const x = Number(node.x);
    const y = Number(node.y);
    if (!Number.isFinite(x) || !Number.isFinite(y)) return 0;
    return Math.hypot(x - destinationX, y - destinationY) * minimumCostPerMapUnit;
  };
}
